// Builds the list of countries a sign-in phone number can be from, with how
// many digits a mobile number has there (India 10, UAE 9, Germany 10 or 11…),
// from Google's libphonenumber data. Writes the same list for the API, the web
// app and the mobile app, so all three accept exactly the same numbers.
//
// Run from this folder:  npm install && npm run generate
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Metadata, getCountries, getCountryCallingCode } from 'libphonenumber-js/max'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const names = new Intl.DisplayNames(['en'], { type: 'region' })
const metadata = new Metadata()

const countries = getCountries()
  .map((iso) => {
    metadata.selectNumberingPlan(iso)
    const plan = metadata.numberingPlan
    // A few small territories list no mobile numbers: take any number there.
    const lengths = plan.type('MOBILE')?.possibleLengths() ?? plan.possibleLengths()
    return {
      iso,
      name: names.of(iso),
      dial: getCountryCallingCode(iso),
      lengths,
      // "0" dialled before a number inside the country (UK 07400…, India 098…)
      // is not part of the number itself.
      trunkZero: plan.nationalPrefix() === '0'
    }
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'en'))

const json = `${JSON.stringify(countries, null, 0).replace(/\},\{/g, '},\n{')}\n`
writeFileSync(join(root, 'Qspot-API/services/phoneCountries.json'), json)
writeFileSync(join(root, 'webapp/src/features/auth/data/phoneCountries.json'), json)

const dartString = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`
const dart = `// GENERATED by tools/phone-countries/generate.mjs. Do not edit by hand.
import 'phone_country.dart';

/// Every country a phone number can be from, A to Z by name.
const phoneCountries = <PhoneCountry>[
${countries
  .map(
    (c) =>
      `  PhoneCountry(iso: '${c.iso}', name: ${dartString(c.name)}, dialCode: '${c.dial}', lengths: [${c.lengths.join(', ')}], trunkZero: ${c.trunkZero}),`
  )
  .join('\n')}
];
`
writeFileSync(join(root, 'mobile-app/lib/screens/auth/model/phone_country_list.dart'), dart)

console.log(`Wrote ${countries.length} countries.`)

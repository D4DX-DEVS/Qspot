// Generates migrations/0001_init.sql: the docs table plus one expression index
// per Mongoose index()/index:true/unique:true declared in src/app/models.
// Re-run after changing a model's indexes (it writes the next numbered file
// only when the SQL differs from the latest generated one).
import Module, { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const shim = path.join(root, 'src/shims/mongoose.js');

const resolve = Module._resolveFilename;
Module._resolveFilename = function (request, ...rest) {
    return request === 'mongoose' ? shim : resolve.call(this, request, ...rest);
};

const modelsDir = path.join(root, 'src/app/models');
for (const f of fs.readdirSync(modelsDir)) if (f.endsWith('.js')) require(path.join(modelsDir, f));
const { __registry } = require(shim);

const col = (p) => `json_extract(data,'$.${p}')`;
const lines = [
    '-- Generated by scripts/gen-migration.mjs. Every model lives in docs(collection,id,data JSON).',
    'CREATE TABLE IF NOT EXISTS docs (',
    '  collection TEXT NOT NULL,',
    '  id TEXT NOT NULL,',
    '  data TEXT NOT NULL,',
    '  PRIMARY KEY (collection, id)',
    ') WITHOUT ROWID;',
    '',
    '-- Counters for the login / OTP rate limits.',
    'CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY, count INTEGER NOT NULL, reset_at INTEGER NOT NULL);',
    '',
    '-- Short-lived values (OTP codes).',
    'CREATE TABLE IF NOT EXISTS kv (key TEXT PRIMARY KEY, value TEXT NOT NULL, expires_at INTEGER NOT NULL);',
    ''
];

const seen = new Set();
const add = (collection, fields, unique) => {
    const name = `idx_${collection}_${fields.join('_')}`.replace(/[^A-Za-z0-9_]/g, '_');
    if (seen.has(name)) return;
    seen.add(name);
    lines.push(`CREATE ${unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS ${name} ON docs(${fields.map(col).join(', ')}) WHERE collection='${collection}';`);
};

for (const [key, model] of __registry) {
    if (key.endsWith('#proxy')) continue;
    const { schema, collection } = model;
    for (const [p, info] of Object.entries(schema.paths)) {
        if (!p.includes('.') && !info.array && (info.index || info.unique)) add(collection, [p], info.unique);
    }
    for (const { fields, options } of schema.indexes) {
        const keys = Object.keys(fields);
        if (keys.some((k) => (schema.paths[k] || {}).array)) continue;
        add(collection, keys, !!options.unique);
    }
}

const out = lines.join('\n') + '\n';
const dir = path.join(root, 'migrations');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, '0001_init.sql'), out);
console.log(`wrote migrations/0001_init.sql (${seen.size} indexes)`);
